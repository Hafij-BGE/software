#!/usr/bin/env bash
# Builds Craft Suite for Windows (64-bit):
#
#   dist/craft-suite_<version>_windows-x64.zip         unzip anywhere, run craft-suite.exe
#   dist/craft-suite_<version>_windows-x64-setup.exe   installer (when Inno Setup's ISCC is found)
#
# The installer puts the suite in Program Files (or, for one user, in their own folder), adds it to
# the Start menu, offers a desktop shortcut, lists it under "Open with" for documents,
# presentations and spreadsheets, and has an uninstaller (Settings › Apps).
#
# Usage: packaging/build-windows.sh [--with-fonts] [--skip-build] [--target TRIPLE]
#   --with-fonts   embed the craft-fonts each upstream release embeds (see build-deb.sh)
#   --skip-build   package what's already built
#   --target       a Rust target to cross-build for (default: the machine's own)
#
# Runs in Git Bash on Windows (as GitHub Actions does), with Rust (MSVC) installed.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
HERE="$ROOT/packaging"
APPS=(wordcraft deckcraft gridcraft)

WITH_FONTS=0
SKIP_BUILD=0
TARGET=""
while [ $# -gt 0 ]; do
  case "$1" in
    --with-fonts) WITH_FONTS=1; shift ;;
    --skip-build) SKIP_BUILD=1; shift ;;
    --target) TARGET="$2"; shift 2 ;;
    -h | --help) sed -n '2,17p' "$0"; exit 0 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

export CARGO_TARGET_DIR="${CARGO_TARGET_DIR:-$ROOT/target}"
DIST="${DIST:-$ROOT/dist}"
mkdir -p "$DIST"
. "$HERE/lib.sh"

REPO="${GITHUB_REPOSITORY:-$(git -C "$ROOT" remote get-url origin 2>/dev/null | sed -nE 's#.*github\.com[:/]([^/]+/[^/.]+)(\.git)?/?$#\1#p')}"
RELEASES_URL="${REPO:+https://github.com/$REPO/releases}"
TARGET_ARGS=()
if [ -n "$TARGET" ]; then TARGET_ARGS=(--target "$TARGET"); fi

echo "==> Craft Suite $VERSION (Windows)"

if [ "$SKIP_BUILD" = 0 ]; then
  for app in "${APPS[@]}"; do
    sha="$(upstream_commit "$app")"
    fonts=""
    if [ "$WITH_FONTS" = 1 ] && [ -n "$(fonts_ref "$app")" ]; then fonts="$(fonts_dir "$(fonts_ref "$app")")"; fi
    upper="$(echo "$app" | tr '[:lower:]' '[:upper:]')"
    echo "==> $app-cli (upstream ${sha:0:8})"
    (cd "$ROOT/upstream/$app" &&
      env "${upper}_BUILD_SHA=$sha" ${fonts:+CRAFT_FONTS_DIR="$fonts"} \
        cargo build --release --locked -p "$app-cli" "${TARGET_ARGS[@]}")
  done
  fonts=""
  if [ "$WITH_FONTS" = 1 ] && [ -n "$(fonts_ref wordcraft)" ]; then fonts="$(fonts_dir "$(fonts_ref wordcraft)")"; fi
  echo "==> craft-suite"
  (cd "$ROOT/suite" &&
    env WORDCRAFT_BUILD_SHA="$(upstream_commit wordcraft)" ${fonts:+CRAFT_FONTS_DIR="$fonts"} \
      ${RELEASES_URL:+CRAFT_SUITE_RELEASES_URL="$RELEASES_URL"} \
      cargo build --release "${TARGET_ARGS[@]}")
fi
BIN="$CARGO_TARGET_DIR/${TARGET:+$TARGET/}release"

# ---- the program folder -------------------------------------------------------------------------
WORK="$ROOT/build/windows"
STAGE="$WORK/Craft Suite"
rm -rf "$WORK"
mkdir -p "$STAGE/licences"
cp "$BIN/craft-suite.exe" "$STAGE/"
for app in "${APPS[@]}"; do cp "$BIN/$app-cli.exe" "$STAGE/"; done
echo "$VERSION" >"$STAGE/VERSION"
upstream_summary >"$STAGE/upstream.txt"
cp "$ROOT/README.md" "$STAGE/README.md"
for app in "${APPS[@]}"; do
  for f in LICENSE-MIT LICENSE-APACHE NOTICE ATTRIBUTION.md; do
    if [ -f "$ROOT/upstream/$app/$f" ]; then cp "$ROOT/upstream/$app/$f" "$STAGE/licences/$app-$f"; fi
  done
done
if [ "$WITH_FONTS" = 1 ]; then
  for d in "$ROOT"/build/craft-fonts-*/fonts/*/; do
    if [ -f "$d/OFL.txt" ]; then cp "$d/OFL.txt" "$STAGE/licences/OFL-$(basename "$d").txt"; fi
  done
fi

NAME="craft-suite_${VERSION//+/-}_windows-x64"

# ---- portable zip -------------------------------------------------------------------------------
rm -f "$DIST/$NAME.zip"
if command -v 7z >/dev/null 2>&1; then
  (cd "$WORK" && 7z a -tzip -bso0 "$DIST/$NAME.zip" "Craft Suite")
elif command -v zip >/dev/null 2>&1; then
  (cd "$WORK" && zip -qr "$DIST/$NAME.zip" "Craft Suite")
else
  powershell -NoProfile -Command "Compress-Archive -Path '$(cygpath -w "$STAGE" 2>/dev/null || echo "$STAGE")' -DestinationPath '$(cygpath -w "$DIST/$NAME.zip" 2>/dev/null || echo "$DIST/$NAME.zip")'"
fi
echo "$DIST/$NAME.zip"

# ---- installer (Inno Setup) ---------------------------------------------------------------------
ISCC="$(command -v iscc 2>/dev/null || command -v ISCC 2>/dev/null || true)"
for p in "/c/Program Files (x86)/Inno Setup 6/ISCC.exe" "/c/Program Files/Inno Setup 6/ISCC.exe"; do
  if [ -z "$ISCC" ] && [ -f "$p" ]; then ISCC="$p"; fi
done
if [ -z "$ISCC" ]; then
  echo "Inno Setup (ISCC) not found: no installer, only the zip"
  exit 0
fi
win() { cygpath -w "$1" 2>/dev/null || echo "$1"; }
ISS="$WORK/craft-suite.iss"
{
  cat <<EOF
; Generated by packaging/build-windows.sh.
[Setup]
AppId={{6F2C9A41-3B7D-4E58-9A16-C2D84B0E7F35}
AppName=Craft Suite
AppVersion=$VERSION
AppVerName=Craft Suite $VERSION
AppPublisher=Craft Suite
AppPublisherURL=${RELEASES_URL:-https://github.com/storytold}
AppUpdatesURL=${RELEASES_URL:-https://github.com/storytold}
DefaultDirName={autopf}\\Craft Suite
DefaultGroupName=Craft Suite
DisableProgramGroupPage=yes
UninstallDisplayIcon={app}\\craft-suite.exe
UninstallDisplayName=Craft Suite
SetupIconFile=$(win "$ROOT/assets/craft-suite.ico")
OutputDir=$(win "$DIST")
OutputBaseFilename=$NAME-setup
Compression=lzma2/max
SolidCompression=yes
ArchitecturesAllowed=x64compatible
ArchitecturesInstallIn64BitMode=x64compatible
PrivilegesRequired=admin
PrivilegesRequiredOverridesAllowed=dialog
ChangesAssociations=yes
CloseApplications=yes
WizardStyle=modern
LicenseFile=$(win "$ROOT/upstream/wordcraft/LICENSE-MIT")

[Tasks]
Name: "desktopicon"; Description: "Create a desktop shortcut"; Flags: unchecked
Name: "openwith"; Description: "List Craft Suite under ""Open with"" for documents, presentations and spreadsheets"

[Files]
Source: "$(win "$STAGE")\\*"; DestDir: "{app}"; Flags: recursesubdirs ignoreversion

[Icons]
Name: "{autoprograms}\\Craft Suite"; Filename: "{app}\\craft-suite.exe"
Name: "{autoprograms}\\WordCraft (Craft Suite)"; Filename: "{app}\\craft-suite.exe"; Parameters: "--new word"
Name: "{autoprograms}\\DeckCraft (Craft Suite)"; Filename: "{app}\\craft-suite.exe"; Parameters: "--new deck"
Name: "{autoprograms}\\GridCraft (Craft Suite)"; Filename: "{app}\\craft-suite.exe"; Parameters: "--new grid"
Name: "{autodesktop}\\Craft Suite"; Filename: "{app}\\craft-suite.exe"; Tasks: desktopicon

[Registry]
Root: HKA; Subkey: "Software\\Classes\\Applications\\craft-suite.exe"; ValueType: string; ValueName: "FriendlyAppName"; ValueData: "Craft Suite"; Flags: uninsdeletekey
Root: HKA; Subkey: "Software\\Classes\\Applications\\craft-suite.exe\\shell\\open\\command"; ValueType: string; ValueData: """{app}\\craft-suite.exe"" ""%1"""
EOF
  # One file type per app, listed under "Open with" for its extensions (not made the default).
  for pair in "Document:docx docm dotx dotm doc dot odt rtf md markdown tex html htm txt" \
    "Presentation:pptx potx ppsx deckcraft" "Spreadsheet:xlsx xlsm xlsb ods csv tsv"; do
    kind="${pair%%:*}" exts="${pair#*:}" progid="CraftSuite.${pair%%:*}"
    cat <<EOF
Root: HKA; Subkey: "Software\\Classes\\$progid"; ValueType: string; ValueData: "$kind (Craft Suite)"; Flags: uninsdeletekey; Tasks: openwith
Root: HKA; Subkey: "Software\\Classes\\$progid\\DefaultIcon"; ValueType: string; ValueData: "{app}\\craft-suite.exe,0"; Tasks: openwith
Root: HKA; Subkey: "Software\\Classes\\$progid\\shell\\open\\command"; ValueType: string; ValueData: """{app}\\craft-suite.exe"" ""%1"""; Tasks: openwith
EOF
    for ext in $exts; do
      echo "Root: HKA; Subkey: \"Software\\Classes\\.$ext\\OpenWithProgids\"; ValueType: string; ValueName: \"$progid\"; ValueData: \"\"; Flags: uninsdeletevalue; Tasks: openwith"
    done
  done
  cat <<EOF

[Run]
Filename: "{app}\\craft-suite.exe"; Description: "Start Craft Suite"; Flags: nowait postinstall skipifsilent
EOF
} >"$ISS"
"$ISCC" //Q "$(win "$ISS")"
echo "$DIST/$NAME-setup.exe"
