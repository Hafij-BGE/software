#!/usr/bin/env python3
"""Seed suite/Cargo.lock with the dependency versions the upstream apps pin.

The suite crate depends on the library crates of WordCraft, DeckCraft and GridCraft, so a fresh
resolve would pick the newest compatible version of every dependency, not the versions upstream
built and tested. This writes the union of the registry and git packages of
upstream/*/Cargo.lock (and of the current suite/Cargo.lock) into suite/Cargo.lock, with every
dependency reference spelled out as "name version" so the union stays unambiguous. Cargo then
keeps those versions where they fit, drops the ones nothing uses and adds what's missing.

Usage: scripts/merge-locks.py            (then: cargo metadata --manifest-path suite/Cargo.toml)
"""
import pathlib
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SUITE_LOCK = ROOT / "suite" / "Cargo.lock"


def load(path):
    with open(path, "rb") as f:
        return tomllib.load(f).get("package", [])


def qualify(packages):
    """Rewrite each dependency reference to "name version" using the lock it came from."""
    versions = {}
    for p in packages:
        versions.setdefault(p["name"], []).append(p["version"])
    out = []
    for p in packages:
        deps = []
        for d in p.get("dependencies", []):
            parts = d.split(" ")
            if len(parts) == 1:
                only = versions.get(parts[0], [])
                if len(only) != 1:
                    raise SystemExit(f"ambiguous dependency {d!r} of {p['name']}")
                deps.append(f"{parts[0]} {only[0]}")
            else:
                deps.append(" ".join(parts[:2]))
        q = dict(p)
        q["dependencies"] = deps
        out.append(q)
    return out


def quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    locks = sorted(ROOT.glob("upstream/*/Cargo.lock"))
    if SUITE_LOCK.exists():
        locks.append(SUITE_LOCK)
    merged = {}
    for lock in locks:
        for p in qualify(load(lock)):
            if "source" not in p:  # a workspace member: cargo adds the ones the suite uses
                continue
            key = (p["name"], p["version"])
            if key in merged and merged[key].get("source") != p.get("source"):
                print(f"warning: {p['name']} {p['version']} comes from two sources; keeping the first", file=sys.stderr)
                continue
            merged.setdefault(key, p)
    lines = [
        "# This file is automatically @generated by Cargo.",
        "# It is not intended for manual editing.",
        "version = 4",
    ]
    for key in sorted(merged):
        p = merged[key]
        lines += ["", "[[package]]", f"name = {quote(p['name'])}", f"version = {quote(p['version'])}"]
        lines.append(f"source = {quote(p['source'])}")
        if "checksum" in p:
            lines.append(f"checksum = {quote(p['checksum'])}")
        if p["dependencies"]:
            lines.append("dependencies = [")
            lines += [f" {quote(d)}," for d in sorted(set(p["dependencies"]))]
            lines.append("]")
    SUITE_LOCK.write_text("\n".join(lines) + "\n")
    print(f"seeded {SUITE_LOCK.relative_to(ROOT)} with {len(merged)} packages from {len(locks)} lockfiles")


if __name__ == "__main__":
    main()
