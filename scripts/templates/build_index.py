#!/usr/bin/env python3
"""Makes templates/index.json (what the Home page lists) and templates/ATTRIBUTION.md from
own.json (make_own.py) and open.json (fetch_open.py), drawing each template's thumbnail with the
suite's own apps: `wordcraft-cli render` for documents, `deckcraft-cli render` for presentations.
Spreadsheet thumbnails are pictures of the suite (shoot_sheets.sh) and are kept as they are.

A template the app can't draw is left out of the index, so the gallery never offers a file that
won't open.

Usage: scripts/templates/build_index.py [templates-dir] [--force]   (--force: draw every thumbnail again)
"""

import json
import os
import shutil
import subprocess
import sys
import tempfile

args = [a for a in sys.argv[1:] if not a.startswith("--")]
FORCE = "--force" in sys.argv
OUT = os.path.abspath(args[0] if args else os.path.join(os.path.dirname(__file__), "../../templates"))
THUMB_W = 360


def load(name):
    p = os.path.join(OUT, name)
    if not os.path.isfile(p):
        return []
    with open(p, encoding="utf-8") as fh:
        return json.load(fh)["templates"]


def shrink(png):
    """Scales a picture down to THUMB_W pixels wide (needs Pillow; left as it is without)."""
    try:
        from PIL import Image
    except ImportError:
        return
    im = Image.open(png).convert("RGB")
    if im.width > THUMB_W:
        im = im.resize((THUMB_W, round(im.height * THUMB_W / im.width)), Image.LANCZOS)
    im.save(png, optimize=True)


def render(src, png):
    """Draws the first page or slide of `src` to `png`; False when the app can't."""
    ext = src.rsplit(".", 1)[-1].lower()
    tool = {"docx": "wordcraft-cli", "pptx": "deckcraft-cli"}.get(ext)
    if not tool or not shutil.which(tool):
        return os.path.isfile(png)
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, "t.png")
        cmd = [tool, "render", src, out, "--scale", "0.6"] if tool == "wordcraft-cli" else \
            [tool, "render", src, "--slide", "0", "--scale", "0.5", out]
        try:
            r = subprocess.run(cmd, capture_output=True, text=True, timeout=180)
        except subprocess.TimeoutExpired:
            print(f"  timed out: {src}")
            return False
        if r.returncode != 0 or not os.path.isfile(out):
            print(f"  can't draw {src}: {(r.stderr or r.stdout).strip()[:200]}")
            return False
        shutil.move(out, png)
    shrink(png)
    return True


def main():
    entries = load("own.json") + load("open.json")
    kept = []
    for e in entries:
        src = os.path.join(OUT, e["file"])
        if not os.path.isfile(src):
            print(f"  missing: {e['file']}")
            continue
        png = src.rsplit(".", 1)[0] + ".png"
        if FORCE or not os.path.isfile(png):
            if not render(src, png) and e.get("source", "").find("Hafij-BGE/software") < 0:
                continue  # an open-licence template the app can't open: left out
        if os.path.isfile(png):
            e["thumbnail"] = os.path.relpath(png, OUT)
        kept.append(e)
    with open(os.path.join(OUT, "index.json"), "w", encoding="utf-8") as fh:
        json.dump({"templates": kept}, fh, indent=1, ensure_ascii=False)
        fh.write("\n")
    write_attribution(kept)
    print(f"{len(kept)} of {len(entries)} templates in {os.path.join(OUT, 'index.json')}")


def write_attribution(entries):
    own = [e for e in entries if "Hafij-BGE/software" in e.get("source", "")]
    other = [e for e in entries if e not in own]
    lines = [
        "# Templates: credits and licences",
        "",
        "Generated by `scripts/templates/build_index.py`; don't edit by hand.",
        "",
        f"## Craft Suite's own ({len(own)})",
        "",
        "Made for Craft Suite by `scripts/templates/make_own.py` and released under",
        "[CC0 1.0](https://creativecommons.org/publicdomain/zero/1.0/): use them for anything, no",
        "credit needed. The names, companies and figures in them are made up.",
        "",
    ]
    lines += [f"- {e['title']} (`{e['file']}`)" for e in own]
    if other:
        lines += [
            "",
            f"## Open-licence templates ({len(other)})",
            "",
            "Collected by `scripts/templates/fetch_open.py` and converted with LibreOffice from their",
            "original OpenDocument files to `.pptx` or `.docx`, so they open in Slide and Word; a",
            "converted template can look a little different from the original. Only templates under CC0,",
            "CC-BY or in the public domain are included. CC-BY templates are credited below, as their",
            "licence asks; keep the credit when you share a copy of the template itself.",
            "",
            "| Template | File | Licence | Author | Source |",
            "|---|---|---|---|---|",
        ]
        for e in other:
            src = e.get("source", "")
            link = f"[{e.get('origin', 'source')}]({src})" if src else ""
            lines.append(f"| {e['title']} | `{e['file']}` | {e.get('license', '')} | {e.get('author', '')} | {link} |")
    with open(os.path.join(OUT, "ATTRIBUTION.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
